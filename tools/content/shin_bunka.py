def reuse(number, index, **changes):
    result = deepcopy(OLD[number]['patterns'][index])
    result.update(changes)
    return result


def new(row):
    fields = row.strip().split('|~|')
    assert len(fields) == 8, fields
    return dict(zip(('title', 'form', 'explanation', 'note', 'example', 'translation', 'practice', 'answer'), fields))


def add(number, title, ja, pages, goal, patterns, extras=(), tags=''):
    for i, pattern in enumerate(patterns, 1):
        pattern.update(id=f'br-{number}-{i}', kind='main', book_ref=f'文型 {i}')
    # 自動詞・他動詞 is the preparatory heading, followed by 文型1 in lesson 25.
    if number == 25:
        patterns[0]['book_ref'] = 'প্রস্তুতি · 自動詞と他動詞'
        patterns[0]['kind'] = 'foundation'
        patterns[1]['book_ref'] = '文型 1'
    for i, (label, pattern) in enumerate(extras, 1):
        pattern.update(id=f'br-{number}-text-{i}', kind='text', book_ref=label)
    LESSONS.append(dict(number=number, title=title, ja=ja, pages=pages, goal=goal,
                        patterns=patterns + [p for _, p in extras], tags=tags))


